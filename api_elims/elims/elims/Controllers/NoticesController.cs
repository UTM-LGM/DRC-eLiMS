        [HttpPost("{id}")]
        public async Task<IActionResult> UploadFile([FromRoute] int id, IFormFile file)
        {
            var details = await _context.Notices.FirstOrDefaultAsync(n => n.Id == id);
            if (details == null)
            {
                return BadRequest("No notice found.");
            }

            if (file == null || file.Length == 0)
            {
                return BadRequest("No file was provided.");
            }

            //var fileExtension = Path.GetExtension(file.FileName);
            var fileName = $"{id}_{details.Announcement}";
            var filePath = Path.Combine(Directory.GetCurrentDirectory(), @"wwwroot\announcement", fileName);

            try
            {
                using (var fileStream = new FileStream(filePath, FileMode.Create))
                {
                    await file.CopyToAsync(fileStream);
                }
                return Ok();
            }
            catch (Exception ex)
            {
                // Log the exception (ex) here if logging is set up in your project
                return StatusCode(500, "An error occurred while uploading the file.");
            }
        }




        // POST: api/Notices
        // To protect from overposting attacks, see https://go.microsoft.com/fwlink/?linkid=2123754
        [HttpPost]
        public async Task<ActionResult<Notice>> PostNotice(Notice notice)
        {
          if (_context.Notices == null)
          {
              return Problem("Entity set 'ElimsContext.Notices'  is null.");
          }
            _context.Notices.Add(notice);
            await _context.SaveChangesAsync();

            return CreatedAtAction("GetNotice", new { id = notice.Id }, notice);
        }

        // DELETE: api/Notices/5
        [HttpDelete("{id}")]
        public async Task<IActionResult> DeleteNotice(int id)
        {
            if (_context.Notices == null)
            {
                return NotFound();
            }
            var notice = await _context.Notices.FindAsync(id);
            if (notice == null)
            {
                return NotFound();
            }

            _context.Notices.Remove(notice);
            await _context.SaveChangesAsync();

            return NoContent();
        }

        private bool NoticeExists(int id)
        {
            return (_context.Notices?.Any(e => e.Id == id)).GetValueOrDefault();
        }
    }
