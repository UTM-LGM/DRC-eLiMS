        [HttpPut]
        public async Task<IActionResult> PutNotices([FromBody] List<Notice> notices)
        {
            if (notices == null || !notices.Any())
            {
                return BadRequest("No notices provided.");
            }

            var ids = notices.Select(n => n.Id).ToList();
            var existingNotices = await _context.Notices
                .Where(x => ids.Contains(x.Id))
                .ToListAsync();

            if (!existingNotices.Any())
            {
                return NotFound("No notices found for the provided IDs.");
            }

            foreach (var notice in notices)
            {
                var existingNotice = existingNotices.FirstOrDefault(n => n.Id == notice.Id);
                if (existingNotice != null)
                {
                    existingNotice.IsShow = notice.IsShow;
                }
            }

            await _context.SaveChangesAsync();

            return NoContent();
        }




        [HttpGet()]
        public async Task<ActionResult<IEnumerable<Notice>>> GetSelectedNotices()
        {
            if (_context.Notices == null)
            {
                return NotFound();
            }

            // Filter notices where isShow is true
            var visibleNotices = await _context.Notices
                .Where(n => n.IsShow == true)
                .ToListAsync();

            return Ok(visibleNotices);
        }



        [HttpPut("{id}")]
        public async Task<IActionResult> PutNoticebyId(int id, Notice notice)
        {
            if (id != notice.Id)
            {
                return BadRequest();
            }

            _context.Entry(notice).State = EntityState.Modified;

            try
            {
                await _context.SaveChangesAsync();
            }
            catch (DbUpdateConcurrencyException)
            {
                if (!NoticeExists(id))
                {
                    return NotFound();
                }
                else
                {
                    throw;
                }
            }

            return NoContent();
        }


